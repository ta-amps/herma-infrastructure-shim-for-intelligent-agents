import { env, exports } from "cloudflare:workers";
import { describe, expect, it } from "vitest";
import {
  BRIDGE_GRID_CONFIG,
  computeTaskFingerprint,
  parseSlugReply,
  scrubSensitiveText,
} from "../deploy/cloudflare/bilateral_bridge.js";

const BASE = "https://herma.ta-amps.workers.dev";

async function callBridge(path, init = {}) {
  return exports.default.fetch(BASE + path, init);
}

describe("bilateral agent transport shim (/bridge/*)", () => {
  it("guards against link-preview false positives on landing and wrong challenge code", async () => {
    const channel = "ch_unit_preview_" + crypto.randomUUID().slice(0, 8);
    const landing = await callBridge(`/bridge/${channel}`);
    expect(landing.status).toBe(200);
    const landingText = await landing.text();
    expect(landingText).toContain("STATUS: READY_FOR_HANDSHAKE");

    const statusBefore = await (await callBridge(`/bridge/${channel}/status`)).json();
    expect(statusBefore.connected_agents).toBe(0);

    const wrongChallenge = await callBridge(`/bridge/${channel}/hello/muse/9999`);
    expect(wrongChallenge.status).toBe(400);
    expect(await wrongChallenge.text()).toContain("HANDSHAKE_CHALLENGE_MISMATCH");

    const statusAfterWrong = await (await callBridge(`/bridge/${channel}/status`)).json();
    expect(statusAfterWrong.connected_agents).toBe(0);
  });

  it("completes GET handshake + GET slug reply + peer POST inbox task handoff with token redaction", async () => {
    const channel = "ch_unit_roundtrip_" + crypto.randomUUID().slice(0, 8);
    const challenge = String(BRIDGE_GRID_CONFIG.challenge_addend_a + BRIDGE_GRID_CONFIG.challenge_addend_b);

    // Operator seeds a specific durable task into the channel inbox
    const seedRes = await callBridge(`/bridge/${channel}/inbox`, {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: JSON.stringify({
        sender: "operator",
        prompts: [
          "Decompose durable queue failover into atomic steps and propose one esoteric chaos task",
        ],
      }),
    });
    expect(seedRes.status).toBe(200);
    const seedJson = await seedRes.json();
    expect(seedJson.queued_count).toBe(1);

    // Turn 1: Muse connects via pure HTTP GET
    const helloRes = await callBridge(`/bridge/${channel}/hello/muse/${challenge}`);
    expect(helloRes.status).toBe(200);
    const helloText = await helloRes.text();
    expect(helloText).toContain("BILATERAL_STATUS: CONNECTED");
    expect(helloText).toContain("AGENT_NAME: muse");
    expect(helloText).toContain("TASK_SOURCE: inbox:operator");
    expect(helloText).toContain("Decompose durable queue failover");

    // Turn 2: Muse replies via pure HTTP GET slug, including a simulated leaked token to verify redaction
    const slug =
      "ack-muse-ready--subtask-validate-outbox-row--subtask-probe-broker-hysteresis--newtask-verify-fenced-lease-replay-tsk_abcdef123456";
    const replyRes = await callBridge(`/bridge/${channel}/reply/muse/t1/${slug}`);
    expect(replyRes.status).toBe(200);
    const replyText = await replyRes.text();
    expect(replyText).toContain("BILATERAL_STATUS: ROUNDTRIP_VERIFIED");
    expect(replyText).toContain("PARSED_SUBTASKS_COUNT: 2");
    expect(replyText).toContain("PARSED_NEWTASKS_COUNT: 1");
    expect(replyText).not.toContain("tsk_abcdef123456");

    // Peer agent Grokbot connects and automatically picks up the task generated by Muse!
    const grokHello = await callBridge(`/bridge/${channel}/hello/grokbot/${challenge}`);
    expect(grokHello.status).toBe(200);
    const grokText = await grokHello.text();
    expect(grokText).toContain("TASK_SOURCE: inbox:muse");
    expect(grokText).toContain("[REDACTED]");
    expect(grokText).not.toContain("tsk_abcdef123456");

    // Status endpoint reflects both connected agents and full redacted transcript
    const statusJson = await (await callBridge(`/bridge/${channel}/status`)).json();
    expect(statusJson.connected_agents).toBe(2);
    expect(statusJson.recent_turns.length).toBeGreaterThanOrEqual(3);
  });

  it("computes deterministic 64-bit SimHash fingerprints and parses structured slugs", async () => {
    const parsed = parseSlugReply(
      "ready--subtask-build-ast-gate--subtask-stage-reusable-kit--blocks-retry-helper--newtask-benchmark-small-adapter"
    );
    expect(parsed.subtasks).toEqual(["build ast gate", "stage reusable kit"]);
    expect(parsed.reusable_blocks).toEqual(["retry helper"]);
    expect(parsed.generated_tasks).toEqual(["benchmark small adapter"]);

    expect(scrubSensitiveText("key hmk_secretvalue12345 and user@example.org")).toBe(
      "key [REDACTED] and [REDACTED]"
    );

    const fp1 = await computeTaskFingerprint("durable task queue lease fencing replay");
    const fp2 = await computeTaskFingerprint("durable task queue lease fencing replay");
    expect(fp1.simhash64_hex).toBe(fp2.simhash64_hex);
    expect(fp1.simhash64_hex).toMatch(/^[0-9a-f]{16}$/);
  });
});
