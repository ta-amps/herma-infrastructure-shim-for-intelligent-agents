// Writes deploy/cloudflare/universal_worker_prompt.js from prompts/universal-worker.txt, byte for byte, so the Worker serves
// the current universal worker prompt at /prompts/raw/universal-worker.txt unchanged (and previous ones at
// /prompts/raw/universal-worker-u6.txt and /prompts/raw/universal-worker-u5.txt).
//   node scripts/sync_universal_prompt.mjs           write the module
//   node scripts/sync_universal_prompt.mjs --check   fail when the module and the text file differ
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
// The newest prompt is prompts/universal-worker.txt; earlier versions stay served as their own .txt files.
const versionOf = (t) => (t.match(/^Version (U\d+), ([A-Za-z]+ \d+, \d{4})/m) || [])[1] || "unknown";
const text = readFileSync(`${root}prompts/universal-worker.txt`, "utf8");
const previousU6 = readFileSync(`${root}prompts/universal-worker-u6.txt`, "utf8");
const previous = readFileSync(`${root}prompts/universal-worker-u5.txt`, "utf8");
const version = versionOf(text);
const out = `// GENERATED by scripts/sync_universal_prompt.mjs from prompts/universal-worker.txt, universal-worker-u6.txt and universal-worker-u5.txt. Do not edit by hand.
export const UNIVERSAL_WORKER_PROMPT_VERSION = ${JSON.stringify(version)};
export const UNIVERSAL_WORKER_PROMPT = ${JSON.stringify(text)};
export const UNIVERSAL_WORKER_PROMPT_U6_VERSION = ${JSON.stringify(versionOf(previousU6))};
export const UNIVERSAL_WORKER_PROMPT_U6 = ${JSON.stringify(previousU6)};
export const UNIVERSAL_WORKER_PROMPT_PREVIOUS_VERSION = ${JSON.stringify(versionOf(previous))};
export const UNIVERSAL_WORKER_PROMPT_PREVIOUS = ${JSON.stringify(previous)};
`;
const target = `${root}deploy/cloudflare/universal_worker_prompt.js`;
if (process.argv.includes("--check")) {
  let have = "";
  try { have = readFileSync(target, "utf8"); } catch {}
  if (have !== out) { console.error("universal_worker_prompt.js is stale: run node scripts/sync_universal_prompt.mjs"); process.exit(1); }
  console.log(`universal prompt ${version}: module matches the text file`);
} else {
  writeFileSync(target, out);
  console.log(`wrote ${target} (${version}, ${text.length} characters)`);
}
