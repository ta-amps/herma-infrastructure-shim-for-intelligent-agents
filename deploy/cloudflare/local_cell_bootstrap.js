    '                    best_r = max(float(prev["best_reward"]), rew)',
    '                    checker = prev["checker_agent"] or (agent_id if prev["producer_agent"] != agent_id else "")',
    '                    self._conn.execute(',
    '                        """UPDATE local_grid_cells',
