function clampInt(rawVal, low, high, fallback) {
  const num = Number(rawVal);
  if (!Number.isFinite(num)) return fallback;
  const rounded = Math.trunc(num);
  if (rounded < low) return low;
  if (rounded > high) return high;
  return rounded;
}

function cleanSafeSlug(rawText, maxLen, fallback) {
  const scrubbed = stripPii(String(rawText || "")).trim();
  const safe = scrubbed.replace(/[^a-zA-Z0-9._-]/g, "-").replace(/-+/g, "-").replace(/^-|-$/g, "").slice(0, maxLen);
  return safe || fallback;
}

function normalizeSyncPolicy(rawPolicy) {
  const candidate = String(rawPolicy || "").trim().toLowerCase();
  const allowed = LOCAL_CELL_BOOTSTRAP_GRID.grid_axes.sync_policy.choices;
  return allowed.includes(candidate) ? candidate : LOCAL_CELL_BOOTSTRAP_GRID.grid_axes.sync_policy.default;
}

